import 'package:flutter/foundation.dart';

/// A single row/column coordinate inside the square letter grid.
@immutable
class GridCoord {
  const GridCoord(this.row, this.col);

  final int row;
  final int col;

  @override
  bool operator ==(Object other) =>
      identical(this, other) ||
      other is GridCoord && row == other.row && col == other.col;

  @override
  int get hashCode => Object.hash(row, col);

  @override
  String toString() => '($row, $col)';
}

/// A target word disguised as a fun riddle or emoji clue in the word bank.
@immutable
class MysteryClue {
  const MysteryClue({
    required this.word,
    required this.clue,
  });

  factory MysteryClue.fromJson(Map<String, dynamic> json) {
    return MysteryClue(
      word: (json['word'] as String).trim().toUpperCase(),
      clue: (json['clue'] as String).trim(),
    );
  }

  final String word;
  final String clue;
}

/// Definition of one puzzle level loaded from the offline JSON asset.
@immutable
class PuzzleLevel {
  const PuzzleLevel({
    required this.levelNumber,
    required this.gridSize,
    required this.seed,
    required this.words,
    required this.mysteryClues,
  });

  factory PuzzleLevel.fromJson(Map<String, dynamic> json) {
    final rawWords = (json['words'] as List<dynamic>).cast<String>();
    final rawClues = (json['mysteryClues'] as List<dynamic>)
        .cast<Map<String, dynamic>>();

    return PuzzleLevel(
      levelNumber: json['levelNumber'] as int,
      gridSize: json['gridSize'] as int,
      seed: json['seed'] as int,
      words: rawWords.map((w) => w.trim().toUpperCase()).toList(),
      mysteryClues: rawClues.map(MysteryClue.fromJson).toList(),
    );
  }

  final int levelNumber;
  final int gridSize;
  final int seed;
  final List<String> words;
  final List<MysteryClue> mysteryClues;

  /// Returns the riddle clue if [word] is a mystery word, or null if plain.
  String? clueForWord(String word) {
    for (final item in mysteryClues) {
      if (item.word == word) return item.clue;
    }
    return null;
  }
}

/// A themed collection of puzzle levels (e.g. Animals, Food & Drink, Space).
@immutable
class WordThemePack {
  const WordThemePack({
    required this.id,
    required this.title,
    required this.subtitle,
    required this.icon,
    required this.accentColorHex,
    required this.levels,
  });

  factory WordThemePack.fromJson(Map<String, dynamic> json) {
    final rawLevels =
        (json['levels'] as List<dynamic>).cast<Map<String, dynamic>>();

    return WordThemePack(
      id: json['id'] as String,
      title: json['title'] as String,
      subtitle: json['subtitle'] as String,
      icon: json['icon'] as String,
      accentColorHex: json['accentColor'] as String,
      levels: rawLevels.map(PuzzleLevel.fromJson).toList(),
    );
  }

  final String id;
  final String title;
  final String subtitle;
  final String icon;
  final String accentColorHex;
  final List<PuzzleLevel> levels;
}

/// Records where a single word was placed inside the generated grid.
@immutable
class PlacedWord {
  const PlacedWord({
    required this.word,
    required this.cells,
    this.clue,
  });

  final String word;
  final List<GridCoord> cells;
  final String? clue;

  GridCoord get start => cells.first;
  GridCoord get end => cells.last;
  bool get isMystery => clue != null;
}

/// Complete playable board generated by [PuzzleGenerator].
@immutable
class GeneratedPuzzle {
  const GeneratedPuzzle({
    required this.size,
    required this.grid,
    required this.placedWords,
  });

  final int size;
  final List<List<String>> grid;
  final List<PlacedWord> placedWords;
}

/// Stores a found word's coordinates and assigned pastel highlighter palette index.
@immutable
class FoundWordHighlight {
  const FoundWordHighlight({
    required this.word,
    required this.cells,
    required this.colorIndex,
  });

  final String word;
  final List<GridCoord> cells;
  final int colorIndex;
}
